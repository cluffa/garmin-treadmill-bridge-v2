/*
 * ssd1306.c — SSD1306 128x64 I2C OLED driver.
 *
 * I2C bus: nrf_drv_twi (legacy layer), 400 kHz.
 *   SDA = PIN_I2C_SDA (P0.04), SCL = PIN_I2C_SCL (P0.05)
 *
 * Framebuffer layout: 8 pages x 128 columns = 1024 bytes.
 *   fb[page * 128 + col] → column bitmask.
 *
 * 5x7 font: 5 column bytes per glyph, rendered with 1 px left padding
 *   → 6 px per character → 21 characters per line.
 *
 * M2 Task 2.3.
 */

