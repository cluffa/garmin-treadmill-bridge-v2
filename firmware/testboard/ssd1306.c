/* ---- I2C helper: send command byte to SSD1306 ------------------------------- */

static void ssd1306_write_cmd(uint8_t cmd)
{
    uint8_t buf[2] = { 0x00, cmd };  /* Co=0, D/C#=0 → command */
    APP_ERROR_CHECK(nrf_drv_twi_tx(&s_twi, 0x3C, buf, 2, false));
}

/* ---- I2C helper: send data to SSD1306 (framebuffer or init bytes) ------------ */

static void ssd1306_write_data(const uint8_t *data, uint16_t len)
{
    /*
     * The SSD1306 expects a control byte (0x40 = Co=0, D/C#=1 → data)
     * followed by the pixel bytes, all in ONE continuous I2C transaction
     * (single START..STOP). Splitting the control byte and the data into two
     * transactions issues a repeated START, after which the SSD1306 treats the
     * next byte as a fresh control byte — corrupting the pixel stream (garbled
     * display). So we prepend 0x40 into a single buffer and send it in one tx.
     *
     * The framebuffer is 1024 bytes; we send one page (128 cols) per
     * transaction. GDDRAM auto-increments across transactions in horizontal
     * addressing mode, so page-sized chunks are fine.
     */
    uint8_t buf[1 + 128];
    while (len > 0) {
        uint16_t chunk = (len > 128) ? 128 : len;

        buf[0] = 0x40;  /* Co=0, D/C#=1 → data */
        memcpy(&buf[1], data, chunk);

        APP_ERROR_CHECK(nrf_drv_twi_tx(&s_twi, 0x3C, buf, chunk + 1, false));
        data += chunk;
        len  -= chunk;
    }
}

/* ---- Initialisation --------------------------------------------------------- */

void ssd1306_init(void)
{
    /* ---- I2C (nrf_drv_twi) ------------------------------------------------- */
    nrf_drv_twi_config_t twi_cfg = {
        .scl                = PIN_I2C_SCL,
        .sda                = PIN_I2C_SDA,
        .frequency          = NRF_DRV_TWI_FREQ_400K,
        .interrupt_priority = APP_IRQ_PRIORITY_LOWEST,
        .clear_bus_init     = false,
        .hold_bus_uninit    = false,
    };
    APP_ERROR_CHECK(nrf_drv_twi_init(&s_twi, &twi_cfg, NULL, NULL));
    nrf_drv_twi_enable(&s_twi);

    /* ---- SSD1306 init sequence (from datasheet) ----------------------------- */

    nrf_delay_ms(10);  /* wait for VDD stabilise */

    /* Display off */
    ssd1306_write_cmd(0xAE);

    /* Set clock divide ratio / oscillator frequency */
    ssd1306_write_cmd(0xD5);
    ssd1306_write_cmd(0x80);  /* default */

    /* Set multiplex ratio */
    ssd1306_write_cmd(0xA8);
    ssd1306_write_cmd(0x3F);  /* 64 */

    /* Set display offset */
    ssd1306_write_cmd(0xD3);
    ssd1306_write_cmd(0x00);

    /* Set display start line */
    ssd1306_write_cmd(0x40);

    /* Set segment re-map: column 127 → SEG0 */
    ssd1306_write_cmd(0xA1);

    /* Set COM output scan direction: remapped (COM[N-1] → COM0) */
    ssd1306_write_cmd(0xC8);

    /* Set COM pins hardware configuration */
    ssd1306_write_cmd(0xDA);
    ssd1306_write_cmd(0x12);

    /* Set contrast */
    ssd1306_write_cmd(0x81);
    ssd1306_write_cmd(0x7F);

    /* Disable entire display on */
    ssd1306_write_cmd(0xA4);

    /* Set normal display (not inverse) */
    ssd1306_write_cmd(0xA6);

    /* Set pre-charge period */
    ssd1306_write_cmd(0xD9);
    ssd1306_write_cmd(0xF1);

    /* Set VCOMH deselect level */
    ssd1306_write_cmd(0xDB);
    ssd1306_write_cmd(0x40);

    /* Enable charge pump regulator */
    ssd1306_write_cmd(0x8D);
    ssd1306_write_cmd(0x14);

    /* Display on */
    ssd1306_write_cmd(0xAF);

    /* Clear framebuffer */
    ssd1306_clear();
}

/* ---- Framebuffer operations ------------------------------------------------- */

void ssd1306_clear(void)
{
    memset(s_fb, 0, sizeof(s_fb));
}

void ssd1306_text(uint8_t col, uint8_t row, const char *text)
{
    if (row >= SSD1306_PAGES) return;

    uint8_t *page = s_fb[row];

    while (*text) {
        if (col > SSD1306_WIDTH - 6) break;  /* no room for next glyph */

        char ch = *text++;
        if (ch < 0x20 || ch > 0x7E) ch = 0x20;  /* replace with space */

        const uint8_t *glyph = font5x7[(uint8_t)(ch - 0x20)];

        /* 1 px left padding, then 5 px glyph, total 6 px */
        for (int i = 0; i < 5; i++) {
            page[col + 1 + i] = glyph[i];
        }
        /* Left pad column is already zero from clear, but ensure it: */
        page[col] = 0x00;

        col += 6;
    }
}

/* ---- Display update --------------------------------------------------------- */

void ssd1306_show(void)
{
    /*
     * Send the entire framebuffer to the GDDRAM.
     * SSD1306 auto-increments column pointers within each page.
     * We set:
     *   addressing mode = horizontal
     *   then for each page: set page address, set column range, write data
     */
    ssd1306_write_cmd(0x20);  /* set memory addressing mode */
    ssd1306_write_cmd(0x00);  /* horizontal addressing mode */

    /* Set column range 0..127 */
    ssd1306_write_cmd(0x21);
    ssd1306_write_cmd(0x00);
    ssd1306_write_cmd(127);

    /* Set page range 0..7 */
    ssd1306_write_cmd(0x22);
    ssd1306_write_cmd(0x00);
    ssd1306_write_cmd(7);

    /* Write entire framebuffer */
    ssd1306_write_data(&s_fb[0][0], sizeof(s_fb));
}
