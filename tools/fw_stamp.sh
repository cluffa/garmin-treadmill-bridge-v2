#!/bin/sh
# Regenerate firmware/build_stamp.c — the firmware's answer to "which image is
# actually on the board?"
#
#   tools/fw_stamp.sh <output.c>
#
# Reported by the USB console's STATUS command as "build". Until 2026-08-11
# there was no way to ask: a DFU that silently did not take, or a package built
# before the fix you are testing, is indistinguishable from a working flash —
# the board comes up and answers either way. The watch side learned this the
# expensive way (see tools/ciq_stamp.sh) and this is the same idea for firmware.
#
# Same MMDD-HHMM convention as the CIQ stamp, so the two can be read side by
# side, plus the git revision, which the watch stamp has no room for. Firmware
# needs the revision because DFU packages persist as files and get flashed days
# later — the timestamp says which *build*, the revision says which *code*.
#
# A trailing '+' means the working tree had uncommitted changes to tracked files
# at build time, so the revision alone does NOT identify the source. Untracked
# files are ignored deliberately: the repo always has untracked .FITs, and a
# marker that is permanently set says nothing.
#
# NOT checked in (see .gitignore) — unlike BuildInfo.mc, which must exist for a
# fresh clone to run a plain `monkeyc`. Firmware only ever builds through the
# Makefile, which regenerates this at parse time before the build graph is
# walked, so a fresh clone always has it in time. Tracking it would also break
# the '+' marker: every build rewrites this file, which would leave the tree
# permanently dirty and the marker permanently set.

OUT="$1"
[ -n "$OUT" ] || { echo "usage: $0 <output.c>" >&2; exit 2; }

# MMDD-HHMM local time — precise enough to tell two builds on the same day
# apart, which is the actual failure mode during a debug session.
STAMP=$(date '+%m%d-%H%M')
ISO=$(date '+%Y-%m-%d %H:%M:%S %Z')

if REV=$(git rev-parse --short HEAD 2>/dev/null); then
    # --quiet HEAD covers staged and unstaged changes to tracked files in one
    # call, and exits non-zero when either exists.
    git diff --quiet HEAD 2>/dev/null || REV="$REV+"
else
    REV="nogit"
fi

# Contract with core/ctrl_dispatch.c: this string is emitted into a JSON value
# unescaped, so it must stay plain ASCII with no '"' and no '\'. date(1) with
# the format above and a git short hash both satisfy that.
cat > "$OUT" <<EOF
/* GENERATED by tools/fw_stamp.sh — do not edit by hand; your change will be
 * overwritten by the next build, and this file is git-ignored.
 *
 * Overrides the weak default in core/ctrl_dispatch.c, so the USB console's
 * STATUS reports which image the board is running. Built: $ISO */
#include "ctrl_dispatch.h"

const char *ctrl_build_stamp(void)
{
    return "$STAMP $REV";
}
EOF

echo "  Firmware stamp: $STAMP $REV"
